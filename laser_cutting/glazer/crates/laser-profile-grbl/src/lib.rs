//! # GRBL 1.1 postprocessor
//!
//! The concrete [`FirmwareProfile`] for GRBL 1.1 (the most common hobby-laser
//! firmware): millimetre units (G21), absolute positioning (G90), G0 rapids,
//! 3-decimal coordinates, M3/M4/M5 laser control. Power percent is mapped
//! through the machine's max S (GRBL `$30`) via `map_power_percent`.
//!
//! Safety: the profile validates that no motion happens while the laser is
//! on unless it is a `LaserMoveTo`, and frame sections never contain M3/M4.

use laser_core::MachineSettings;
use laser_gcode::{
    fmt_coord, map_power_percent, validate_program, FirmwareCapabilities, FirmwareProfile,
    GcodeError, PostprocessSettings, PowerMode,
};
use laser_planner::{MotionOp, MotionPlan};

/// Profile id stored in `ExportSettings` and project files.
pub const PROFILE_ID: &str = "grbl-1.1";

pub struct Grbl11Profile {
    caps: FirmwareCapabilities,
}

impl Default for Grbl11Profile {
    fn default() -> Self {
        Self {
            caps: FirmwareCapabilities {
                profile_id: PROFILE_ID.into(),
                display_name: "GRBL 1.1".into(),
                tested_versions: vec!["1.1f".into(), "1.1h".into()],
                documentation_url: "https://github.com/gnea/grbl/blob/master/doc/markdown/laser_mode.md"
                    .into(),
                units_mm: true,
                g20_g21: true,
                absolute_positioning: true,
                coordinate_decimals: 3,
                rapid_is_g0: true,
                rapid_guarantees_laser_off: false,
                supports_m3: true,
                supports_m4: true,
                supports_m5: true,
                supports_arcs: false,
                min_feed_mm_min: 1.0,
                max_feed_mm_min: 100_000.0,
                default_max_s: 1000.0,
            },
        }
    }
}

impl FirmwareProfile for Grbl11Profile {
    fn capabilities(&self) -> &FirmwareCapabilities {
        &self.caps
    }

    fn postprocess(
        &self,
        plan: &MotionPlan,
        machine: &MachineSettings,
        settings: &PostprocessSettings,
    ) -> Result<String, GcodeError> {
        if !self.caps.supports_m5 {
            return Err(GcodeError::Refused(
                "GRBL profile cannot guarantee laser-off travel without M5".into(),
            ));
        }
        let max_s = if machine.max_s_value > 0.0 {
            machine.max_s_value
        } else {
            settings.max_s
        };
        let decimals = self.caps.coordinate_decimals;
        let mut out = String::new();
        let mut frame_lines: Vec<usize> = Vec::new();
        let mut in_frame = false;
        let mut current_feed: Option<f64> = None;
        let mut line_index = 0usize;

        fn push_line(out: &mut String, line_index: &mut usize, line: &str, frame_lines: &mut Vec<usize>, in_frame: bool) {
            out.push_str(line);
            out.push('\n');
            if in_frame {
                frame_lines.push(*line_index);
            }
            *line_index += 1;
        }

        push_line(&mut out, &mut line_index, "; Generated by Glazer", &mut frame_lines, false);
        push_line(&mut out, &mut line_index, "; Profile: GRBL 1.1", &mut frame_lines, false);
        push_line(&mut out, &mut line_index, "; Units: mm", &mut frame_lines, false);
        push_line(&mut out, &mut line_index, "; Preflight: verify $32 laser mode and $30 max spindle/laser S on the controller. This app does not write controller settings.", &mut frame_lines, false);
        push_line(&mut out, &mut line_index, "G21", &mut frame_lines, false);
        push_line(&mut out, &mut line_index, "G90", &mut frame_lines, false);
        push_line(&mut out, &mut line_index, "G17", &mut frame_lines, false);
        push_line(&mut out, &mut line_index, "G94", &mut frame_lines, false);
        push_line(&mut out, &mut line_index, "M5", &mut frame_lines, false);

        for op in &plan.ops {
            match op {
                MotionOp::Comment { text } => {
                    in_frame = text.to_ascii_lowercase().contains("frame");
                    push_line(
                        &mut out,
                        &mut line_index,
                        &format!("; {text}"),
                        &mut frame_lines,
                        in_frame,
                    );
                }
                MotionOp::LaserOff => {
                    push_line(&mut out, &mut line_index, "M5", &mut frame_lines, in_frame);
                }
                MotionOp::RapidTo { to } => {
                    push_line(&mut out, &mut line_index, "M5", &mut frame_lines, in_frame);
                    let line = format!(
                        "G0 X{} Y{}",
                        fmt_coord(to.x, decimals),
                        fmt_coord(to.y, decimals)
                    );
                    push_line(&mut out, &mut line_index, &line, &mut frame_lines, in_frame);
                }
                MotionOp::SetLaser {
                    power_percent,
                    dynamic,
                } => {
                    if in_frame {
                        return Err(GcodeError::Refused(
                            "frame operations cannot enable the laser".into(),
                        ));
                    }
                    let s = map_power_percent(*power_percent, max_s)?;
                    let cmd = if *dynamic
                        && settings.default_power_mode == PowerMode::DynamicM4
                    {
                        "M4"
                    } else {
                        "M3"
                    };
                    if cmd == "M4" && !self.caps.supports_m4 {
                        return Err(GcodeError::Refused("profile does not support M4".into()));
                    }
                    push_line(
                        &mut out,
                        &mut line_index,
                        &format!("{cmd} S{s}"),
                        &mut frame_lines,
                        in_frame,
                    );
                }
                MotionOp::LaserMoveTo {
                    to,
                    feed_mm_min,
                    power_percent: _,
                } => {
                    if *feed_mm_min < self.caps.min_feed_mm_min
                        || *feed_mm_min > self.caps.max_feed_mm_min
                    {
                        return Err(GcodeError::Refused(format!(
                            "feed {feed_mm_min} mm/min is outside profile limits"
                        )));
                    }
                    let mut line = format!(
                        "G1 X{} Y{}",
                        fmt_coord(to.x, decimals),
                        fmt_coord(to.y, decimals)
                    );
                    if current_feed != Some(*feed_mm_min) {
                        line.push_str(&format!(" F{}", fmt_coord(*feed_mm_min, 1)));
                        current_feed = Some(*feed_mm_min);
                    }
                    push_line(&mut out, &mut line_index, &line, &mut frame_lines, in_frame);
                }
                MotionOp::LaserOffMoveTo { to, feed_mm_min } => {
                    push_line(&mut out, &mut line_index, "M5", &mut frame_lines, in_frame);
                    let mut line = format!(
                        "G1 X{} Y{}",
                        fmt_coord(to.x, decimals),
                        fmt_coord(to.y, decimals)
                    );
                    if current_feed != Some(*feed_mm_min) {
                        line.push_str(&format!(" F{}", fmt_coord(*feed_mm_min, 1)));
                        current_feed = Some(*feed_mm_min);
                    }
                    push_line(&mut out, &mut line_index, &line, &mut frame_lines, in_frame);
                }
                MotionOp::ProgramEnd => {
                    push_line(&mut out, &mut line_index, "; End of job", &mut frame_lines, false);
                    push_line(&mut out, &mut line_index, "M5", &mut frame_lines, false);
                    push_line(&mut out, &mut line_index, "M2", &mut frame_lines, false);
                    in_frame = false;
                }
            }
        }

        validate_program(&out, |i| frame_lines.contains(&i))?;
        Ok(out)
    }
}

#[cfg(test)]
mod tests {
    use laser_core::{
        Affine, Bounds2D, DocumentId, ObjectId, PathGeometry, PathObject, PathSegment, PointMm,
        Project, SourceFormat, SourceMetadata, SourceStyle, Subpath, UnitMetadata, VectorDocument,
    };
    use laser_gcode::FirmwareProfile;
    use laser_planner::{plan_project, PlanOptions};

    use super::*;

    #[test]
    fn golden_square() {
        let geometry = PathGeometry {
            subpaths: vec![Subpath {
                start: PointMm { x: 0.0, y: 0.0 },
                segments: vec![
                    PathSegment::LineTo {
                        to: PointMm { x: 10.0, y: 0.0 },
                    },
                    PathSegment::LineTo {
                        to: PointMm { x: 10.0, y: 10.0 },
                    },
                ],
                closed: false,
            }],
        };
        let document = VectorDocument {
            id: DocumentId::new(),
            units: UnitMetadata::known(laser_core::LengthUnit::Millimeter),
            bounds_mm: Bounds2D {
                min: PointMm::origin(),
                max: PointMm { x: 10.0, y: 10.0 },
            },
            objects: vec![PathObject {
                id: ObjectId::new(),
                geometry,
                style: SourceStyle::default(),
                source: SourceMetadata {
                    format: SourceFormat::Generated,
                    file_name: "t".into(),
                    source_id: None,
                    source_layer: None,
                    entity_type: "path".into(),
                    original_color: None,
                },
                layer_id: None,
                visible: true,
                export_enabled: true,
            }],
            import_warnings: vec![],
            source_to_canonical: Affine::identity(),
            source_format: SourceFormat::Generated,
            source_file_name: "t".into(),
        };
        let mut project = Project::from_document(document);
        // Layers are no longer created from a colour palette on import, so
        // tests create the process layer they need explicitly.
        let mut layer = laser_core::ProcessLayer::new(
            "Cut",
            laser_core::Rgba8::rgb(255, 0, 0),
            0,
            laser_core::OperationKind::Cut,
        );
        layer.speed_mm_min = 600.0;
        layer.power_percent = 70.0;
        layer.laser_mode = laser_core::LaserMode::Dynamic;
        let id = layer.id;
        project.layers.push(layer);
        project.document.objects[0].layer_id = Some(id);
        project.job.offset_mm = PointMm::origin();
        project.job.origin_mode = laser_core::OriginMode::Source;
        project.job.scale = 1.0;
        project.job.rotation_deg = 0.0;

        let plan = plan_project(&project, PlanOptions::default()).unwrap();
        let gcode = Grbl11Profile::default()
            .postprocess(
                &plan,
                &project.machine,
                &PostprocessSettings {
                    max_s: 1000.0,
                    default_power_mode: PowerMode::DynamicM4,
                },
            )
            .unwrap();
        assert!(gcode.contains("G21"));
        assert!(gcode.contains("M5"));
        assert!(gcode.contains("M4 S700"));
        assert!(gcode.contains("G1 X10.000 Y0.000 F600.0"));
        assert!(gcode.contains("M2"));
        assert!(!gcode.split("M4").next().unwrap().contains("G1 X"));
        let last_m5 = gcode.rfind("M5").unwrap();
        let last_m2 = gcode.rfind("M2").unwrap();
        assert!(last_m5 < last_m2);
    }
}
